    /// <summary>Gets the frozen Profile 1 operation identities in ordinal order.</summary>
    internal static IReadOnlyList<string> Profile1 { get; } = Array.AsReadOnly(Profile1Identities);

    /// <summary>Resolves the frozen Profile 1 identities to exact registry instances.</summary>
    internal static MathBlockOperation[] ResolveProfile1(MathBlockRegistry registry)
    {
        var byIdentity = new Dictionary<string, MathBlockOperation>(StringComparer.Ordinal);
        for (var index = 0; index < registry.Operations.Count; index++)
            byIdentity.Add(registry.Operations[index].Identity, registry.Operations[index]);

        var result = new MathBlockOperation[Profile1Identities.Length];
        for (var index = 0; index < result.Length; index++)
        {
            if (!byIdentity.TryGetValue(Profile1Identities[index], out var operation))
            {
                throw new InvalidOperationException(
                    $"Profile 1 operation '{Profile1Identities[index]}' is missing from the standard catalog.");
            }
            result[index] = operation;
        }
        return result;
    }

    /// <summary>Resolves every registry operation for Profile 2 in registry order.</summary>
    internal static MathBlockOperation[] ResolveProfile2(MathBlockRegistry registry)
    {
        var result = MathBlockCollectionPrimitives.Copy(registry.Operations);
        if (result.Length != Profile2OperationCount)
        {
            throw new InvalidOperationException(
                $"Profile 2 requires exactly {Profile2OperationCount} operations.");
        }
        return result;
    }
